/** Formater un nombre en notation lisible (1 234 567) */
export function formatXp(n: number): string {
  if (n >= 1_000_000_000) {
    const b = n / 1_000_000_000;
    return b % 1 === 0 ? `${b} G` : `${b.toFixed(1)} G`;
  }
  if (n >= 1_000_000) {
    const m = n / 1_000_000;
    return m % 1 === 0 ? `${m} M` : `${m.toFixed(1)} M`;
  }
  if (n >= 1_000) {
    const k = n / 1_000;
    return k % 1 === 0 ? `${k} K` : `${k.toFixed(1)} K`;
  }
  return n.toLocaleString('fr-FR');
}
